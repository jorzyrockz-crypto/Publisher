export function buildMasterPresetElements(
  presetId: string,
  pageWidth: number,
  pageHeight: number,
  margins: PageMargins,
  projectName = 'Publication'
): PublisherElement[] {
  const ts = Date.now();
  const contentW = Math.max(160, pageWidth - margins.left - margins.right);
  const cleanTitle = projectBaseName(projectName).toUpperCase();

  switch (presetId) {
    case 'corporate-header-footer':
      return [
        {
          id: `mst-hdr-${ts}`,
          type: 'text',
          name: 'Master Header Title',
          x: margins.left,
          y: 16,
          width: contentW,
          height: 24,
          rotation: 0,
          zIndex: 1,
          text: cleanTitle,
          fontFamily: 'Segoe UI',
          fontSize: 10,
          fontWeight: 'bold',
          fontStyle: 'normal',
          textDecoration: 'none',
          letterSpacing: 2,
          color: '#64748b',
          textAlign: 'left',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
        {
          id: `mst-rule-${ts}`,
          type: 'line',
          name: 'Master Footer Line',
          x: margins.left,
          y: pageHeight - 38,
          width: contentW,
          height: 4,
          rotation: 0,
          zIndex: 1,
          strokeColor: '#cbd5e1',
          strokeWidth: 1.5,
        },
        {
          id: `mst-pg-${ts}`,
          type: 'text',
          name: 'Master Page Token',
          x: margins.left,
          y: pageHeight - 32,
          width: contentW,
          height: 22,
          rotation: 0,
          zIndex: 2,
          text: 'Page {{page}} of {{total}}',
          fontFamily: 'Segoe UI',
          fontSize: 10,
          fontWeight: 'normal',
          fontStyle: 'normal',
          textDecoration: 'none',
          color: '#64748b',
          textAlign: 'right',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
      ];

    case 'magazine-folio':
      return [
        {
          id: `mst-mag-top-${ts}`,
          type: 'text',
          name: 'Magazine Issue Line',
          x: margins.left,
          y: 14,
          width: contentW,
          height: 20,
          rotation: 0,
          zIndex: 1,
          text: `${cleanTitle}  •  SPECIAL EDITION`,
          fontFamily: 'Georgia',
          fontSize: 9,
          fontWeight: 'bold',
          fontStyle: 'normal',
          textDecoration: 'none',
          letterSpacing: 3,
          color: '#94a3b8',
          textAlign: 'center',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
        {
          id: `mst-mag-num-${ts}`,
          type: 'text',
          name: 'Editorial Folio',
          x: margins.left,
          y: pageHeight - 34,
          width: contentW,
          height: 24,
          rotation: 0,
          zIndex: 2,
          text: '— {{page}} —',
          fontFamily: 'Georgia',
          fontSize: 12,
          fontWeight: 'bold',
          fontStyle: 'italic',
          textDecoration: 'none',
          color: '#334155',
          textAlign: 'center',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
      ];

    case 'program-border':
      return [
        {
          id: `mst-prg-bdr-${ts}`,
          type: 'shape',
          name: 'Master Decorative Frame',
          shapeType: 'rounded-rect',
          x: 24,
          y: 24,
          width: Math.max(120, pageWidth - 48),
          height: Math.max(120, pageHeight - 48),
          rotation: 0,
          zIndex: 1,
          fillColor: 'transparent',
          strokeColor: '#cbd5e1',
          strokeWidth: 2,
          cornerRadius: 14,
        },
        {
          id: `mst-prg-ft-${ts}`,
          type: 'text',
          name: 'Program Footer',
          x: margins.left,
          y: pageHeight - 42,
          width: contentW,
          height: 20,
          rotation: 0,
          zIndex: 2,
          text: `${cleanTitle}  •  Page {{page}}`,
          fontFamily: 'Georgia',
          fontSize: 10,
          fontWeight: 'normal',
          fontStyle: 'italic',
          textDecoration: 'none',
          color: '#64748b',
          textAlign: 'center',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
      ];

    case 'brand-watermark':
      return [
        {
          id: `mst-wm-badge-${ts}`,
          type: 'shape',
          name: 'Brand Corner Badge',
          shapeType: 'rounded-rect',
          x: pageWidth - margins.right - 130,
          y: 16,
          width: 130,
          height: 24,
          rotation: 0,
          zIndex: 1,
          fillColor: '#f1f5f9',
          strokeColor: '#cbd5e1',
          strokeWidth: 1,
          cornerRadius: 12,
          label: cleanTitle.slice(0, 14),
          labelColor: '#475569',
          labelFontSize: 9,
        },
        {
          id: `mst-wm-pg-${ts}`,
          type: 'text',
          name: 'Page Number',
          x: margins.left,
          y: pageHeight - 30,
          width: contentW,
          height: 20,
          rotation: 0,
          zIndex: 2,
          text: '{{page}}',
          fontFamily: 'Segoe UI',
          fontSize: 10,
          fontWeight: 'bold',
          fontStyle: 'normal',
          textDecoration: 'none',
          color: '#94a3b8',
          textAlign: 'right',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
      ];

    case 'booklet-footer':
    default:
      return [
        {
          id: `mst-bk-line-${ts}`,
          type: 'line',
          name: 'Booklet Divider',
          x: margins.left,
          y: pageHeight - 40,
          width: contentW,
          height: 4,
          rotation: 0,
          zIndex: 1,
          strokeColor: '#e2e8f0',
          strokeWidth: 1,
        },
        {
          id: `mst-bk-pg-${ts}`,
          type: 'text',
          name: 'Booklet Page Number',
          x: margins.left,
          y: pageHeight - 34,
          width: contentW,
          height: 22,
          rotation: 0,
          zIndex: 2,
          text: 'Page {{page}}',
          fontFamily: 'Segoe UI',
          fontSize: 10,
          fontWeight: 'bold',
          fontStyle: 'normal',
          textDecoration: 'none',
          color: '#64748b',
          textAlign: 'center',
          verticalAlign: 'middle',
          columns: 1,
          columnGap: 10,
          lineHeight: 1.2,
          padding: 0,
        },
      ];
  }
}
